/* CASE STATEMENT */
/* GRADE */
SELECT *,
	CASE
		WHEN SCORE >= 94 THEN "A"
        WHEN SCORE >= 90 THEN "A-"
        WHEN SCORE >= 87 THEN "B+"
        WHEN SCORE >= 83 THEN "B"
        WHEN SCORE >= 80 THEN "B-"
        WHEN SCORE >= 77 THEN "C+"
        WHEN SCORE >= 73 THEN "C"
        WHEN SCORE >= 70 THEN "C-"
        WHEN SCORE >= 67 THEN "D+"
        WHEN SCORE >= 60 THEN "D"
        ELSE "F"
	END AS GRADE
FROM STUDENTS_GRADES ORDER BY SCORE DESC;

/* COUNT OF STUDENTS */
SELECT
	CASE 
		WHEN SCORE >= 94 THEN "A"
        WHEN SCORE >= 90 THEN "A-"
        WHEN SCORE >= 87 THEN "B+"
        WHEN SCORE >= 83 THEN "B"
        WHEN SCORE >= 80 THEN "B-"
        WHEN SCORE >= 77 THEN "C+"
        WHEN SCORE >= 73 THEN "C"
        WHEN SCORE >= 70 THEN "C-"
        WHEN SCORE >= 67 THEN "D+"
        WHEN SCORE >= 60 THEN "D"
        ELSE "F"
	END AS GRADE,
    COUNT(*) AS NUMBER_OF_STUDENTS
FROM STUDENTS_GRADES
GROUP BY GRADE
ORDER BY
	CASE 
		WHEN GRADE = 'A' THEN 1
		WHEN GRADE = 'A-' THEN 2
        WHEN GRADE = 'B+' THEN 3
        WHEN GRADE = 'B' THEN 4
        WHEN GRADE = 'B-' THEN 5
        WHEN GRADE = 'C+' THEN 6
        WHEN GRADE = 'C' THEN 7
        WHEN GRADE = 'C-' THEN 8
        WHEN GRADE = 'D+' THEN 9
        WHEN GRADE = 'D-' THEN 10
        ELSE 11
	END;

/* PASS OR FAIL */
SELECT
	CASE 
		WHEN score >= 60
			THEN "Passed"
		ELSE "Failed"
	END AS Result,
	COUNT(*) AS Number_of_Students
FROM Students_Grades
GROUP BY Result
ORDER BY Result DESC;


