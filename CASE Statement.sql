ADD COLUMN STATE VARCHAR(50),
ADD COLUMN PIN_CODE VARCHAR(10);

SELECT (CASE 
	WHEN FULL_ADDRESS REGEXP '[0-9]{6}$' THEN SUBSTRING(FULL_ADDRESS,LENGTH(FULL_ADDRESS) - 5, 6)
	WHEN FULL_ADDRESS REGEXP '[0-9]{6}' THEN SUBSTRING(FULL_ADDRESS,LOCATE('-',FULL_ADDRESS)+2, 6)
    ELSE null 
END) AS PIN_CODE FROM ADDRESS_DATA;

UPDATE ADDRESS_DATA
SET PIN_CODE = CASE 
	WHEN FULL_ADDRESS REGEXP '[0-9]{6}$' THEN SUBSTRING(FULL_ADDRESS,LENGTH(FULL_ADDRESS) - 5, 6)
	WHEN FULL_ADDRESS REGEXP '[0-9]{6}' THEN SUBSTRING(FULL_ADDRESS,LOCATE('-',FULL_ADDRESS)+2, 6)
    ELSE null 
END,
CITY = CASE
    WHEN FULL_ADDRESS LIKE '%,%' THEN TRIM(SUBSTRING_INDEX(FULL_ADDRESS, ',', 1))
    WHEN FULL_ADDRESS LIKE '%-%' THEN TRIM(SUBSTRING_INDEX(FULL_ADDRESS, '-', 1))
    ELSE TRIM(SUBSTRING_INDEX(FULL_ADDRESS, ' ', 1))
END,
STATE = CASE 
	WHEN FULL_ADDRESS LIKE '%,%' THEN TRIM(SUBSTRING_INDEX(SUBSTRING_INDEX(FULL_ADDRESS, ',', -1),'-',1))
    WHEN FULL_ADDRESS LIKE '%-%' THEN TRIM(SUBSTRING_INDEX(SUBSTRING_INDEX(FULL_ADDRESS, '-', -1),',',-1))
    ELSE TRIM(SUBSTRING_INDEX(SUBSTRING_INDEX(FULL_ADDRESS, ' ', -3),' ',2))
END;

