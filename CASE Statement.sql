DELIMITER $$
CREATE PROCEDURE Student_Case(IN S_Sub VARCHAR(30), OUT S_Course VARCHAR(30))
BEGIN 
	DECLARE sub VARCHAR (20);
    SELECT subject INTO sub FROM Student WHERE subject = S_Sub;
    CASE sub
		WHEN 'Computer' THEN 
			SET S_Course = 'B.Tech';
		WHEN 'History' THEN 
			SET S_Course = 'BA';
		ELSE 
			SET S_Course = 'Subject is not available';
	END CASE;
END$$
