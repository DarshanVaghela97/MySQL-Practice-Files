/*--ROLLUP OPERATIONS
  --COALESCE() FUNCTION RETURNS THE FIRST NON-NULL VALUE IN A LIST
  --ROLLUP IN SQL AGGREGATION IS USED TO PERFORM MULTIPLE LEVELS OF
    SUBTOTALS AND A GRAND TOTAL, WHICH HELPS IN SUMARIZING DATA ACROSS MULTIPLE DIMENSIONS
*/

SELECT COALESCE (DEPARTMENT, 'All DEPARTMENTS') AS DEPARTMENT,
sum(SALARY) AS SALARY_SUM
FROM EMPLOYEE1
GROUP BY DEPARTMENT WITH ROLLUP;

SELECT 
COALESCE (DEPARTMENT, 'All DEPARTMENTS') AS DEPARTMENT,
COALESCE (GENDER, 'All GENDER') AS GENDER,
sum(SALARY) AS SALARY_SUM
FROM EMPLOYEE1
GROUP BY DEPARTMENT,GENDER WITH ROLLUP;

SELECT 
COALESCE (DEPARTMENT, 'All DEPARTMENTS') AS DEPARTMENT,
COALESCE (GENDER, 'All GENDER') AS GENDER,
sum(SALARY) AS SALARY_SUM
FROM EMPLOYEE1
GROUP BY CUBE DEPARTMENT,GENDER;

-- MySQL doesn't actually support CUBE at all, even with correct syntax. It only supports ROLLUP (via WITH ROLLUP)
-- CUBE is a thing in SQL Server, Postgres, Oracle — 
-- but MySQL never implemented it. So this will throw a syntax error no matter how you format it. --

SELECT 
COALESCE (DEPARTMENT, 'All DEPARTMENTS') AS DEPARTMENT,
COALESCE (GENDER, 'All GENDER') AS GENDER,
sum(SALARY) AS SALARY_SUM
FROM EMPLOYEE1
GROUP BY DEPARTMENT,GENDER WITH CUBE;

