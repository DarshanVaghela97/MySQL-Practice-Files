-- YEAR DIFFERENCE with month --
DELIMITER $$
CREATE PROCEDURE YEARDIFFERENCE(IN STARTDATE DATE,IN ENDDATE DATE, DIFF VARCHAR(20))
BEGIN 
DECLARE YEAR_DIFF INT;
DECLARE MONTH_DIFF INT;
DECLARE TOTAL_MONTH_DIFF INT;
SET YEAR_DIFF = YEAR(ENDDATE) - YEAR(STARTDATE);
SET MONTH_DIFF = MONTH(ENDDATE) - MONTH(STARTDATE);
SET TOTAL_MONTH_DIFF = (YEAR_DIFF * 12) + MONTH_DIFF;
SET DIFF = CONCAT(YEAR_DIFF, ' YEAR ', MOD(TOTAL_MONTH_DIFF,12), ' MONTH');
END$$
DELIMITER ;

CALL YEARDIFFERENCE('1995-01-01',CURRENT_DATE(),@DIFF);
