-- YEAR DIFFERENCE WITH MONTH AND DAYS --
DELIMITER $$
CREATE PROCEDURE AGEDIFFERENCE(IN STARTDATE DATE, IN ENDDATE DATE, OUT DIFF VARCHAR(30))
BEGIN
DECLARE YEAR_DIFF INT;
DECLARE MONTH_DIFF INT;
DECLARE DAY_DIFF INT;
SET YEAR_DIFF = TIMESTAMPDIFF(YEAR, STARTDATE,ENDDATE);
