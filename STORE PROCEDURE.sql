CREATE Function Factorial (n int) RETURNS DOUBLE
DETERMINISTIC
BEGIN
DECLARE fact DOUBLE DEFAULT 1;
DECLARE counter INT DEFAULT 1;
WHILE counter <=n DO
SET fact = fact * counter;
SET counter = counter + 1;
END WHILE;
RETURN fact;
END$$ 
