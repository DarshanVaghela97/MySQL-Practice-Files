-- Procedure for Handling Transactions with Rollback --
CREATE TABLE ACCOUNTS (ACCOUNT_ID INT AUTO_INCREMENT PRIMARY KEY, ACCOUNT_NAME VARCHAR(255),BAlANCE DECIMAL(10,2));
