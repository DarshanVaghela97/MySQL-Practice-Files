/* Function to Discount on Customer Type */
DELIMITER //
CREATE FUNCTION GETDISCOUNT (CUSTOMERTYPE VARCHAR(10))
RETURNS DECIMAL(5,2)
DETERMINISTIC
BEGIN 
	DECLARE DISCOUNT DECIMAL(5,2);
    IF CUSTOMERTYPE = 'REGULAR' THEN
		SET DISCOUNT = 0.05;
	ELSEIF CUSTOMERTYPE = 'VIP' THEN
		SET DISCOUNT = 0.10;
	ELSEIF CUSTOMERTYPE = 'EMPLOYEE' THEN
		SET DISCOUNT = 0.20;
	ELSE 
		SET DISCOUNT = 0.00;
	END IF;
    RETURN DISCOUNT;
END //
DELIMITER ;

SELECT GETDISCOUNT ('REGULAR') AS DISCOUNT;

/* Function to Determin Tax Rate Based on Income */
DELIMITER //
CREATE FUNCTION GETTAXRATE (INCOME DECIMAL (10,2))
RETURNS DECIMAL (4,2)
DETERMINISTIC
BEGIN
	DECLARE TAXRATE DECIMAL (4,2);
    IF INCOME < 20000 THEN
		SET TAXRATE = 0.10;
	ELSEIF INCOME BETWEEN 20000 AND 50000 THEN
		SET TAXRATE = 0.20;
	ELSE 
		SET TAXRATE = 0.30;
	END IF;
    RETURN TAXRATE;
END //
DELIMITER ;

SELECT GETTAXRATE(60000) AS TAXRATE;

DELIMITER //
CREATE FUNCTION GETPAYABLETAXRATE(INCOME INT)
RETURNS VARCHAR(50)
DETERMINISTIC
BEGIN
	DECLARE TAXRATE VARCHAR(50);
    IF INCOME < 20000 THEN
		SET TAXRATE = 0.10;
	ELSEIF INCOME BETWEEN 20000 AND 50000 THEN
		SET TAXRATE = 0.30;
	END IF;
    RETURN TAXRATE;
END //
DELIMITER ;

SET @INCOME = 35550;
SET @TAXRATE = GETPAYABLETAXRATE(@INCOME);
SET @PAYTAX = @INCOME * @TAXRATE;
SELECT @INCOME AS INCOME, CONCAT(@TAXRATE*100,'%') AS TAXRATE, CONCAT('Rs.',@PAYTAX) AS PAYTAX;

/* Function to Determine Grade Based on Score */
DELIMITER //
CREATE FUNCTION GETGRADE (SCORE INT)
RETURNS CHAR(1)
DETERMINISTIC
BEGIN
	DECLARE GRADE CHAR(1);
    IF SCORE >=90 THEN
		SET GRADE = 'A';
	ELSEIF SCORE >= 80 THEN
		SET GRADE = 'B';
	ELSEIF SCORE >=70 THEN
		SET GRADE = 'C';
	ELSEIF SCORE >=60 THEN
		SET GRADE = 'D';
	ELSE 
		SET GRADE = 'F';
	END IF;
    RETURN GRADE;
END //
DELIMITER ;

SELECT GETGRADE(95) AS GRADE;

/* Function to Calculate Shipping Cost Based on Weight */
DELIMITER //
CREATE FUNCTION GETSHIPPINGCOST (WEIGHT DECIMAL(10,2))
RETURNS VARCHAR(50)
DETERMINISTIC
BEGIN 
	DECLARE SHIPPINGCOST VARCHAR(50);
    IF WEIGHT <=1.0 THEN
		SET SHIPPINGCOST = CONCAT(FORMAT(5.00, 2),'₹', ' FOR WEIGHT UPTO 1Kg');
	ELSEIF WEIGHT <=5.0 THEN
		SET SHIPPINGCOST = CONCAT(FORMAT(10.00, 2),'₹', ' FOR WEIGHT BETWEEN 1Kg AND 5Kg');
	ELSE
		SET SHIPPINGCOST = CONCAT(FORMAT(20.00, 2),'₹', ' FOR WEIGHT ABOVE 5Kg');
	END IF;
RETURN SHIPPINGCOST;
END //
DELIMITER ;

SELECT GETSHIPPINGCOST(0.75) AS SHIPPINGCOST;
SELECT GETSHIPPINGCOST(4.5) AS SHIPPINGCOST;
SELECT GETSHIPPINGCOST(6.0) AS SHIPPINGCOST;
SELECT QUANTITY,GETSHIPPINGCOST(QUANTITY) AS SHIPPINGCOST FROM SALES1;

