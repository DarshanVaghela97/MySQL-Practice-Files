SELECT SALESPERSON, SALES_DATE, AMOUNT,
SUM(AMOUNT) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS RUNNING_TOTAL 
FROM SALES;

## Row Number()
SELECT SALESPERSON, SALES_DATE, AMOUNT,
ROW_NUMBER() OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS ROW_NUM
FROM SALES;

## RANK()
SELECT SALESPERSON, SALES_DATE, AMOUNT,
RANK() OVER (PARTITION BY SALESPERSON ORDER BY AMOUNT DESC) AS SALES_RANK
FROM SALES;

## DENSE RANK()
SELECT SALESPERSON, SALES_DATE, AMOUNT,
DENSE_RANK() OVER (PARTITION BY SALESPERSON ORDER BY AMOUNT DESC) AS DENSE_SALES_RANK
FROM SALES;

