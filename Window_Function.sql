## Moving Average
SELECT SALESPERSON, SALES_DATE, AMOUNT, AVG(AMOUNT)
OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE)
AS MOVING_AVERAGE FROM SALES;

## LAG FUNCTION
SELECT SALESPERSON, SALES_DATE, AMOUNT,
LAG(AMOUNT, 1) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS PREVIOUS_AMOUNT
FROM SALES;

## LEAD FUNCTION 
SELECT SALESPERSON, SALES_DATE, AMOUNT,
LEAD(AMOUNT, 1) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS NEXT_AMOUNT
FROM SALES;

## FIRST VALUE 
SELECT SALESPERSON, SALES_DATE, AMOUNT,
FIRST_VALUE(AMOUNT) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS FIRST_AMOUNT
FROM SALES;

## LAST VALUE 
SELECT SALESPERSON, SALES_DATE, AMOUNT,
LAST_VALUE(AMOUNT) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE
ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS LAST_AMOUNT
FROM SALES;

## PERCENT RANK
SELECT SALESPERSON, SALES_DATE, AMOUNT,
PERCENT_RANK() OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS `PERCENT_RANK`
FROM SALES;

## CUME_DIST (CUMALATIVE DISTRIBUTION)
SELECT SALESPERSON, SALES_DATE, AMOUNT,
CUME_DIST() OVER (PARTITION BY SALESPERSON ORDER BY AMOUNT DESC) AS CUMULATIVE_DIST
FROM SALES;

## NTILE
SELECT SALESPERSON, SALES_DATE, AMOUNT,
NTILE(4) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE) AS QUARTILE
FROM SALES;

## FIRST AND LAST VALUeS WITH SPECIFIED WINDOW FRAME
SELECT SALESPERSON, SALES_DATE, AMOUNT,
FIRST_VALUE(AMOUNT) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE
ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS FIRST_AMOUNT,
LAST_VALUE(AMOUNT) OVER (PARTITION BY SALESPERSON ORDER BY SALES_DATE
ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS LAST_AMOUNT
FROM SALES;